/**
 * TLS options for postgres.js. Local development databases connect without TLS; Supabase hosts
 * use full verification (chain + hostname) against Node's roots plus the pinned Supabase root;
 * every other host uses postgres.js "verify-full" with Node's default roots.
 */
export function postgresTlsOptions(databaseUrl: string, localDevelopment: boolean) {
    if (localDevelopment) return false as const
    let hostname = ""
    try {
        hostname = new URL(databaseUrl).hostname.toLowerCase()
    } catch {
        return "verify-full" as const
    }
    if (hostname.endsWith(".supabase.com") || hostname.endsWith(".supabase.co")) {
        return {
            rejectUnauthorized: true,
            ca: [...rootCertificates, SUPABASE_ROOT_2021_CA],
        }
    }
    return "verify-full" as const
}
